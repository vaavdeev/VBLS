import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from scipy.stats import gumbel_l   # gumbel_l = Gumbel for MINIMA (SEV);
                                   # its CDF 1-exp(-exp((x-mu)/beta)) is exactly
                                   # the survival/CDF written in §16.2.4 (3.71x).
                                   # NB: gumbel_r (maxima) would be the WRONG sign.

# ── Plot style (shared across all VBLS figure scripts; cosmetic only) ─────────
plt.rcParams.update({
    'font.family':       'DejaVu Serif',
    'font.size':         11,
    'axes.titlesize':    12,
    'axes.labelsize':    11,
    'xtick.labelsize':   10,
    'ytick.labelsize':   10,
    'axes.spines.top':   False,
    'axes.spines.right': False,
    'axes.grid':         True,
    'grid.alpha':        0.22,
    'grid.linestyle':    '--',
    'lines.linewidth':   2.0,
    'figure.dpi':        150,
})

# ── Global parameters ─────────────────────────────────────────────────────────
# Fixed seed => byte-for-byte reproducible figure. The conclusions (Gumbel in B,
# straight mid-life hazard in C) hold for any seed; only the finite-sample noise
# in the tails changes.
np.random.seed(42)

# Illustrative constants in NORMALISED time. None is calibrated to data.
nu_eff = 0.08    # late-phase effective decay rate of R(t), used only in Panel A
R_star = 0.25    # critical repair-reserve threshold R* (death when R<=R*)
t_max  = 60.0    # plot horizon for Panel A (dimensionless time units)
t      = np.linspace(0, t_max, 1000)

fig, axes = plt.subplots(2, 2, figsize=(11, 8.5))
fig.subplots_adjust(hspace=0.38, wspace=0.35)

# ══════════════════════════════════════════════════════════════════════════════
# Panel A — Where the spread of t_R comes from (deterministic R(t) trajectories)
# ══════════════════════════════════════════════════════════════════════════════
# In the late phase the VBLS equation for the repair reserve reduces to
#   dR/dt ≈ -(nu_0 + nu*Sigma_late) R  ≡  -nu_eff R    =>   R(t) = R0 * e^{-nu_eff t}
# (this is the model's own late-phase approximation, eq. 16.2.4 Step 3, not an
# ad-hoc choice). Six individuals with different initial reserves R0 are shown
# only to make visible that variability in R0 -> a spread of crossing times t_R
# (the dots on R = R*). That spread is exactly what becomes the t_R distribution
# fed into Panels B–C. The specific R0 list is illustrative.
R0_vals  = [0.95, 0.90, 0.85, 0.80, 0.75, 0.70]
colors_A = plt.cm.Blues(np.linspace(0.45, 0.90, len(R0_vals)))

ax = axes[0, 0]
for R0, col in zip(R0_vals, colors_A):
    R_t = R0 * np.exp(-nu_eff * t)
    ax.plot(t, R_t, color=col, lw=1.8)
    idx = np.where(R_t <= R_star)[0]            # first time R(t) drops to R*
    if len(idx):
        ax.plot(t[idx[0]], R_star, 'o', color=col, ms=5, zorder=5)

ax.axhline(R_star, color='red', linestyle='--', lw=1.6, label=r'$R^*$')
ax.set_xlabel('Time $t$ (normalised)')
ax.set_ylabel('Repair reserve $R(t)$')
ax.set_title(r'(A) Trajectories of $R(t)$')
ax.set_ylim(0, 1.02)
ax.legend(fontsize=10)

# ══════════════════════════════════════════════════════════════════════════════
# Panel B — Population law of t_B = min(t_E, t_R) is Gumbel (smallest extreme val)
# ══════════════════════════════════════════════════════════════════════════════
# MECHANISTIC GENERATION (no Gumbel is assumed; it EMERGES):
#   For each of n_pop individuals we draw n_comp independent repair-pathway
#   "exhaustion times" and take their MINIMUM (weakest link = first pathway to
#   fail, §16.2.4 Step 3a). Because we take a minimum over many i.i.d. variables,
#   the Fisher–Tippett–Gnedenko theorem guarantees convergence to the Gumbel
#   (minimum/SEV) law. We then FIT that same law to the generated sample — i.e.
#   we test the theorem, we do not impose its conclusion.
#
#   * component distribution = Normal(49, 15): a generic light-tailed law on the
#     real line (its left tail puts it in the SEV min-domain of attraction). The
#     numbers 49/15/n_comp=50 only set where the histogram sits on the t-axis;
#     they do NOT create the Gumbel shape — any light-tailed component law with
#     enough components gives the same shape.
#   * `indiv` = small per-individual offset: genetic/epigenetic between-subject
#     variability; widens the population law, does not change its family.
#   * t_E = Exponential(scale=140): the MINOR E-channel (rare early catastrophic
#     failure). R-channel dominates by construction (§16.2.4 Step 1), exactly as
#     the theory states; t_E only adds a small low-age background.
n_pop, n_comp = 6000, 50
indiv   = np.random.normal(0.0, 2.5, size=n_pop)            # between-individual spread
comp    = np.random.normal(49.0, 15.0, size=(n_pop, n_comp))
t_R_pop = comp.min(axis=1) + indiv                          # R-channel: first-pathway failure
t_E_pop = np.random.exponential(scale=140, size=n_pop)      # minor E-channel
t_B_pop = np.minimum(t_R_pop, t_E_pop)                      # death = first channel to fire
t_B_pop = t_B_pop[t_B_pop > 0]

# Fit the SEV/Gumbel-min law to the SIMULATED deaths (parameters are OUTPUTS of
# the fit, not inputs we chose).
loc_g, scale_g = gumbel_l.fit(t_B_pop)
t_fit = np.linspace(t_B_pop.min(), t_B_pop.max(), 400)

ax = axes[0, 1]
ax.hist(t_B_pop, bins=60, density=True, color='steelblue', alpha=0.55,
        label='VBLS population')
ax.plot(t_fit, gumbel_l.pdf(t_fit, loc_g, scale_g),
        color='crimson', lw=2.2,
        label=f'Gumbel (min) fit\n$\\mu$={loc_g:.1f}, $\\beta$={scale_g:.1f}')
ax.set_xlabel('Death time $t_B$')
ax.set_ylabel('Probability density')
ax.set_title(r'(B) Distribution of $t_B = \min(t_E,\,t_R)$')
ax.legend(fontsize=9)

# ══════════════════════════════════════════════════════════════════════════════
# Panel C — EMPIRICAL hazard of the simulated population vs a Gompertz line
# ══════════════════════════════════════════════════════════════════════════════
# We do NOT re-plot an analytic hazard. We estimate the hazard directly from the
# t_B sample of Panel B with the standard actuarial life-table estimator:
#     mu_hat(t_i) = (deaths in [t_i, t_i+dt]) / (number alive at t_i * dt).
# This closes the chain A -> B -> C using one and the same simulated cohort.
dt_bin   = 1.5
edges    = np.arange(0, t_B_pop.max() + dt_bin, dt_bin)
deaths,_ = np.histogram(t_B_pop, bins=edges)
centers  = 0.5 * (edges[:-1] + edges[1:])
n_total  = len(t_B_pop)
at_risk  = n_total - np.concatenate(([0], np.cumsum(deaths)[:-1]))  # survivors at t_i
with np.errstate(divide='ignore', invalid='ignore'):
    mu_hat = deaths / (at_risk * dt_bin)
# Drop bins with too few survivors (estimator unstable in the extreme tail).
mask     = (at_risk > 30) & (deaths > 0)
t_emp    = centers[mask]
mu_emp   = mu_hat[mask]

# HONEST REFERENCE LINE: the Gompertz line is fitted to the MID-LIFE window only
# (percentiles 25–85 of the deaths), deliberately leaving the tails un-fitted so
# their deviations are visible and auditable:
#   * young ages -> a near-constant floor (Makeham-like background from t_E);
#   * old ages   -> a downward bend (late-life mortality deceleration / plateau).
# Both deviations are PREDICTED by the model, not artefacts; a global fit would
# have masked them.  b is the OUTPUT slope, reported in the legend.
lo, hi   = np.percentile(t_B_pop, [25, 85])
fit_mask = (t_emp >= lo) & (t_emp <= hi)
b_emp, lna_emp = np.polyfit(t_emp[fit_mask], np.log(mu_emp[fit_mask]), 1)
t_line  = np.linspace(t_emp.min(), t_emp.max(), 200)
mu_line = np.exp(lna_emp) * np.exp(b_emp * t_line)

ax = axes[1, 0]
ax.semilogy(t_emp, mu_emp, 'o', color='steelblue', ms=5, alpha=0.8,
            label='Empirical hazard\n(VBLS population)')
ax.semilogy(t_line, mu_line, color='crimson', lw=2.0, linestyle='--',
            label=f'Gompertz fit (mid-life)\n$b={b_emp:.3f}$')
ax.set_xlabel('Time $t$')
ax.set_ylabel('Mortality intensity $\\mu(t)$')
ax.set_title('(C) Empirical hazard vs Gompertz line')
ax.legend(fontsize=9)

# ══════════════════════════════════════════════════════════════════════════════
# Panel D — Two regimes set by nu_eff, plus the Makeham background (schematic)
# ══════════════════════════════════════════════════════════════════════════════
# These curves are explicitly ANALYTIC and SCHEMATIC (no data, no fitting). Their
# sole purpose is to show that one control parameter, nu_eff = nu_0 + nu*Sigma_late
# (which sets the hazard slope b ∝ nu_eff, §16.2.4 Step 5), maps onto two textbook
# mortality regimes (§16.2.6) WITHOUT changing the model structure, while the
# additive Makeham background A is NOT set by nu_eff (a separate fast channel):
#   * pure Gompertz     : nu ~ 0  => nu_eff = nu_0 (low)  => gentle straight line
#   * Gompertz–Makeham  : same slope + age-independent background A (outside
#                          nu_eff) => low-age floor
#   * plateau           : Sigma_late -> 1 => nu_eff at its ceiling nu_0 + nu (high)
#                          => steepest early rise, then SATURATES (deceleration)
# The constants below are chosen only for visual separation of the three shapes.
t_d = np.linspace(30, 110, 400)

# Pure Gompertz and Gompertz–Makeham deliberately SHARE one nu_eff-driven slope;
# Makeham differs from pure Gompertz solely by the additive background A (=0.012),
# so the reader sees that "Makeham" is "Gompertz + constant", nothing more.
gomp = 1.0e-3 * np.exp(0.085 * (t_d - 50))
mu1  = gomp                       # pure Gompertz  (a*e^{b t})
mu2  = 0.012 + gomp               # Gompertz–Makeham  (A + a*e^{b t})

# Plateau: a steeper base (highest nu_eff) passed through a saturating map
#   mu = mu_cap * g / (mu_cap + g)  ->  follows g at small g, tends to mu_cap.
# This encodes the ceiling nu_eff <= nu_0 + nu: the hazard cannot grow without
# bound, producing the late-life plateau. mu_cap is an illustrative ceiling.
mu_cap = 0.30
g3     = 6.0e-4 * np.exp(0.130 * (t_d - 50))
mu3    = mu_cap * g3 / (mu_cap + g3)

ax = axes[1, 1]
ax.semilogy(t_d, mu1, color='steelblue', lw=2.2,
            label='Pure Gompertz ($\\nu\\approx0$)')
ax.semilogy(t_d, mu2, color='darkorange', lw=2.2, linestyle='-.',
            label='Gompertz–Makeham (+ background $A$)')
ax.semilogy(t_d, mu3, color='seagreen', lw=2.2, linestyle='--',
            label='Plateau ($\\Sigma_{late}\\to1$)')
ax.set_xlabel('Age (years)')
ax.set_ylabel('Mortality intensity $\\mu(t)$')
ax.set_title('(D) Two regimes from $\\nu_{eff}$, plus background $A$')
ax.legend(fontsize=9)
ax.set_xlim(30, 110)
ax.set_ylim(1e-4, 1.5)

# ── Save ──────────────────────────────────────────────────────────────────────
out = 'gompertz_comparison_4panels.png'
fig.savefig(out, dpi=200, bbox_inches='tight')
print(f'Saved: {out}')
